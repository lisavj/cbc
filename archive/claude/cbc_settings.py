#!/usr/bin/env python3
"""Extract CBC input defaults from a CBC_v*.pine file -> markdown (claude/CBC_SETTINGS.md).
Usage: python3 cbc_settings.py CBC_v10_87.pine > CBC_SETTINGS.md
Lists every input whose variable starts with ats_, bot_, xr_, ema_, htf_, mtf_, alert_ or vwap_ (the replay-relevant ones first)."""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
ver = re.search(r'indicator\("([^"]+)"', src).group(1)
rx = re.compile(r'^(\w+)\s*=\s*input(?:\.(\w+))?\(\s*("(?:[^"\\]|\\.)*"|[^,()]+(?:\([^()]*\))?)\s*,\s*"((?:[^"\\]|\\.)*)"', re.M)
KEY = ['ats_slx_sym', 'ats_atr_m1', 'ats_min_sl', 'ats_msl_sym', 'ats_cap_txt', 'ats_tp1_sym', 'ats_atr_t1', 'ats_tpc_txt', 'ats_part_pct', 'ats_part_sym', 'ats_pw_sym',
       'ats_be_on', 'ats_be_sym', 'ats_trail_on', 'ats_trail_m0', 'ats_trail_m', 'ats_trl_sym', 'ats_rp_sym', 'ats_rpz_sym', 'ats_f_ext_sym', 'ats_f_flip_sym', 'ats_fw_sym', 'ats_fw2_sym',
       'ats_mtg_sym', 'ats_tw_sym', 'ema_s_sym', 'ema_f_sym', 'xr_cut_sym', 'xr_cut_min', 'xr_cut_pct', 'xr_cut_x', 'xr_lock_sym', 'xr_lock_at', 'xr_lock_to', 'xr_bot',
       'bot_sym', 'bot_win', 'bot_d5', 'bot_noet', 'bot_eodt', 'bot_mode', 'bot_qty', 'bot_risk', 'bot_t_fl', 'bot_t_ly', 'bot_t_ln', 'bot_t_ll', 'bot_t_h9', 'bot_t_h20', 'bot_t_mo', 'bot_t_pb', 'bot_t_tc']
rows = {m.group(1): (m.group(2) or '', m.group(3).strip(), m.group(4).strip()) for m in rx.finditer(src)}
out = ['# CBC settings (defaults) — %s' % ver, '', 'Generated by claude/cbc_settings.py from the newest pine/CBC_v*.pine in the project. Defaults only: the user may have changed inputs on a chart.', '',
       '## Replay-relevant inputs', '', '| Variable | Label | Default |', '|---|---|---|']
for k in KEY:
    if k in rows: out.append('| %s | %s | `%s` |' % (k, rows[k][2].replace('|', '/'), rows[k][1].replace('|', '/')))
out += ['', '## Other ats_ / bot_ / xr_ / ema_ inputs', '', '| Variable | Label | Default |', '|---|---|---|']
for k, (t, d, l) in rows.items():
    if k not in KEY and re.match(r'(ats_|bot_|xr_|ema_)', k): out.append('| %s | %s | `%s` |' % (k, l.replace('|', '/'), d.replace('|', '/')))
log = re.findall(r'^// (v10\.\d+ \(\d\d/\d\d/\d{4}\):.{0,220})', src, re.M)[:8]
out += ['', '## Latest changelog entries (first 220 chars)', ''] + ['- ' + x.replace('|', '/') for x in log]
print('\n'.join(out))
